      <section class="about-section" aria-labelledby="about-intro-title">
        <h2 id="about-intro-title">
          Apa itu LINNMS?
        </h2>

        <p>
          <strong>LINNMS</strong> adalah aplikasi
          <em>Network Management System (NMS)</em> yang dikembangkan
          untuk membantu operator jaringan dalam memantau, mengelola,
          dan memahami kondisi infrastruktur jaringan melalui
          satu platform terpusat.
        </p>

        <p>
          LINNMS berfokus pada kebutuhan monitoring dan pengelolaan
          perangkat jaringan, khususnya infrastruktur berbasis
          <strong>OLT (Optical Line Terminal)</strong> dan
          <strong>ONU (Optical Network Unit)</strong> yang digunakan
          pada jaringan fiber optik, termasuk
          <em>Fiber to the Home (FTTH)</em>.
        </p>

        <p>
          Melalui antarmuka yang terstruktur, LINNMS menyajikan
          informasi perangkat, aktivitas jaringan, dan notifikasi
          untuk membantu operator memahami kondisi operasional
          serta menelusuri perangkat yang membutuhkan pemeriksaan.
        </p>
      </section>

